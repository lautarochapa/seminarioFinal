const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require(require.resolve('jsdom', {paths:[path.join(__dirname,'../../mobile')]}));
const read = file => fs.readFileSync(path.join(__dirname,'../..',file),'utf8');
const flush = () => new Promise(resolve => setImmediate(resolve));
(async () => {
  const parsed = new JSDOM(read('resources/views/web/user-screen.blade.php'));
  const markup = parsed.window.document.querySelector('[data-user-budget]').outerHTML;
  parsed.window.close();
  const dom = new JSDOM(markup,{url:'http://localhost/web/budget',runScripts:'outside-only'});
  const w = dom.window, d = w.document;
  w.HTMLElement.prototype.scrollIntoView = function () {};
  w.HTMLDialogElement.prototype.showModal = function () {this.setAttribute('open','');};
  w.HTMLDialogElement.prototype.close = function () {this.removeAttribute('open');this.dispatchEvent(new w.Event('close'));};
  const budget = {id:1,year:2026,month:9,total_amount:10000,used_amount:100,available_amount:9900,currency:'ARS'};
  let categories = [], calls = [];
  w.CCApi = {request:async (url, options = {}) => {
    if (options.method) {
      calls.push({url,method:options.method,body:options.body});
      if (options.body.amount > 10000) throw {payload:{error:{message:'La asignacion supera el total del presupuesto.'}}};
      if (options.method === 'PATCH') categories[0] = {...categories[0],amount:options.body.amount};
      else categories.push({id:categories.length+1,amount:options.body.amount,product_category_id:options.body.product_category_id||null,ingredient_category_id:options.body.ingredient_category_id||null,product_category_name:options.body.product_category_id?'Lacteos':null,ingredient_category_name:options.body.ingredient_category_id?'Vegetales':null,spent_amount:options.body.product_category_id?100:null,available_amount:options.body.product_category_id?options.body.amount-100:null});
      return {data:categories[categories.length-1]};
    }
    if (url.endsWith('/product-categories')) return {data:[{id:7,name:'Alimentos',children:[{id:8,name:'Lacteos',children:[]}]}]};
    if (url.endsWith('/ingredient-categories')) return {data:[{id:10,name:'Vegetales',children:[]}]};
    if (url === '/api/v1/family-groups') return {data:[{id:1,name:'Hogar local'}]};
    if (url.endsWith('/budgets/current')) return {data:budget};
    if (url.endsWith('/categories')) return {data:categories};
    if (url.includes('/budgets?')) return {data:[budget],meta:{total:1,current_page:1,last_page:1}};
    throw Error('Unexpected request '+url);
  }};
  await new Promise(resolve => d.addEventListener('DOMContentLoaded',resolve,{once:true}));
  w.eval(read('public/js/panel-ui.js')); w.eval(read('public/js/user-budget.js'));
  d.dispatchEvent(new w.Event('DOMContentLoaded')); await flush();
  d.querySelector('[data-budget-cats]').click(); await flush();
  const form = d.querySelector('[data-budget-cat-form]');
  const submit = async () => {form.dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));await flush();};
  w.CCUI.reveal(form);
  form.elements.category_choice.value = 'product:8'; form.elements.amount.value = '6000';
  await submit();
  assert.deepEqual(JSON.parse(JSON.stringify(calls[0].body)),{amount:6000,product_category_id:8});
  assert.ok(!form.closest('dialog').open);
  assert.match(d.querySelector('[data-budget-cats-list]').textContent,/Lacteos/);
  assert.match(d.querySelector('[data-budget-cats-allocation]').textContent,/6\.000,00/);
  d.querySelector('[data-cat-edit]').click();
  assert.ok(form.closest('dialog').open);
  assert.equal(form.elements.amount.value,'6000');
  assert.ok(form.elements.category_choice.disabled);
  form.elements.amount.value = '3000'; await submit();
  assert.equal(calls[1].method,'PATCH');
  assert.deepEqual(JSON.parse(JSON.stringify(calls[1].body)),{amount:3000});
  assert.ok(!form.elements.category_choice.disabled);
  w.CCUI.reveal(form); form.elements.category_choice.value = 'ingredient:10'; form.elements.amount.value = '2000'; await submit();
  assert.deepEqual(JSON.parse(JSON.stringify(calls[2].body)),{amount:2000,ingredient_category_id:10});
  assert.match(d.querySelector('[data-budget-cats-list]').textContent,/Vegetales/);
  w.CCUI.reveal(form); form.elements.category_choice.value = 'product:7'; form.elements.amount.value = '11000'; await submit();
  assert.ok(form.closest('dialog').open);
  assert.match(form.closest('dialog').textContent,/La asignacion supera/);
  dom.window.close();
  console.log('PASS: budget category catalogs, create/edit API contract, totals, nullable spending and modal errors.');
})().catch(error=>{console.error(error);process.exitCode=1;});
